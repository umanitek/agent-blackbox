"""The shell launchers that start a program inside the profile: one per command-line agent (first on
the person's PATH), the Hermes agent's sandboxed shells and its ``execute_code`` interpreter launcher.

Usage::

    launcher_script("claude", here, profile)
    shell_shim("bash", here, profile, launchers)
    command_shim(profile, launchers)
"""

from __future__ import annotations

from .profile import PROFILE_SUFFIX, SANDBOX_EXEC
from .tools import tools_dir


def with_tools(tools: str) -> str:
    """The shell lines that put the sandbox's tools first on PATH, for the sandboxed program only."""
    return f"""tools={quote_shell(tools)}
if [ -d "$tools" ]; then PATH="$tools:$PATH"; export PATH; fi
"""


#: The index of an agent's project profiles beside its profile (``profiles.INDEX``).
PROJECT_INDEX = "projects.idx"
#: Allow once for a profile's permission: ``<profile>.once.sb`` beside the profile the launch picks;
#: the launch that MOVES it to ``<profile>.run.<pid>.sb`` (a rename: only one of two launches can)
#: runs in it, if it is younger than :data:`ONCE_MINUTES`.
ONCE_SUFFIX, RUN_INFIX, ONCE_MINUTES = ".once" + PROFILE_SUFFIX, ".run.", 30


def pick_profile() -> str:
    """The shell lines that swap ``$profile`` (the agent's own) for its project profile: the LONGEST
    folder in ``<profile without suffix>/projects.idx`` that holds the physical working folder
    (``pwd -P``). The folder goes to awk through the environment, so a backslash in it stays as it
    is; no index, no match or an unreadable file keeps the agent's own profile. Exports the
    profile chosen (``BLACKBOX_SANDBOX_PROFILE``) for the session's records. An allow-once profile
    beside the chosen one (:data:`ONCE_SUFFIX`) is taken by this launch alone (see there)."""
    return f"""projects="${{profile%{PROFILE_SUFFIX}}}"
if [ -r "$projects/{PROJECT_INDEX}" ]; then
  found=$(BLACKBOX_CWD="$(pwd -P 2>/dev/null)" awk -F '\t' 'BEGIN {{ d = ENVIRON["BLACKBOX_CWD"] }}
    length($1) > n && (d == $1 || index(d, $1 "/") == 1) {{ n = length($1); best = $2 }} END {{ print best }}' "$projects/{PROJECT_INDEX}")
  if [ -n "$found" ] && [ -r "$projects/$found" ]; then profile="$projects/$found"; fi
fi
once="${{profile%{PROFILE_SUFFIX}}}{ONCE_SUFFIX}"
if [ -f "$once" ]; then
  taken="${{profile%{PROFILE_SUFFIX}}}{RUN_INFIX}$${PROFILE_SUFFIX}"
  if mv "$once" "$taken" 2>/dev/null; then
    if [ -n "$(find "$taken" -mmin -{ONCE_MINUTES} 2>/dev/null)" ]; then profile="$taken"; else rm -f "$taken"; fi
  fi
fi
digest=$(sed -n '2s/.*sha256:\\([0-9a-f]*\\).*/\\1/p' "$profile" 2>/dev/null)
BLACKBOX_SANDBOX_PROFILE="$profile#$digest"; export BLACKBOX_SANDBOX_PROFILE
"""


def launcher_script(command: str, here: str, profile: str) -> str:
    """The launcher put first on PATH for *command*: finds the real program further down PATH and
    runs it inside the profile, with the sandbox's tools (``<here>/sandbox-tools``) first on ITS
    PATH. Already inside a sandbox (an agent starting another) it runs the program as it is — the
    sandbox it is in still applies. No profile: Blackbox's hooks only, said on stderr (fail-open: an
    agent always starts)."""
    return f"""#!/bin/sh
# Blackbox agent sandbox launcher for {command} — generated by Blackbox (File Shield), rewritten on change.
here={quote_shell(here)}
profile={quote_shell(profile)}
path_rest=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$here" | paste -sd: -)
real=$(PATH="$path_rest" command -v {quote_shell(command)}) || {{ echo "blackbox: {command} is not installed" >&2; exit 127; }}
if [ "${{BLACKBOX_AGENT_SANDBOX:-}}" = 1 ]; then exec "$real" "$@"; fi
{pick_profile()}if [ -r "$profile" ]; then
  BLACKBOX_AGENT_SANDBOX=1; export BLACKBOX_AGENT_SANDBOX
  {with_tools(tools_dir(here)).strip().replace(chr(10), chr(10) + "  ")}
  exec {SANDBOX_EXEC} -f "$profile" "$real" "$@"
fi
echo "blackbox: no sandbox profile — {command} runs with Blackbox's hooks only" >&2
exec "$real" "$@"
"""


def quote_shell(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"

def shell_shim(shell: str, here: str, profile: str, launchers: str = "") -> str:
    """A ``bash`` / ``sh`` / ``zsh`` that runs the real shell inside the profile — put first on the
    Hermes agent's OWN PATH (never the person's), so every shell its terminal tool starts is inside
    the sandbox while the Hermes process itself (and Blackbox in it) stays outside. *launchers*:
    the folder whose ``sandbox-tools`` go first on the sandboxed shell's PATH."""
    return f"""#!/bin/sh
# Blackbox agent sandbox: {shell} for the Hermes agent's tools — generated by Blackbox (File Shield).
here={quote_shell(here)}
profile={quote_shell(profile)}
path_rest=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$here" | paste -sd: -)
real=$(PATH="$path_rest" command -v {quote_shell(shell)}) || real=/bin/{shell}
if [ "${{BLACKBOX_AGENT_SANDBOX:-}}" = 1 ] || [ ! -r "$profile" ]; then exec "$real" "$@"; fi
{pick_profile()}BLACKBOX_AGENT_SANDBOX=1; export BLACKBOX_AGENT_SANDBOX
{with_tools(tools_dir(launchers)) if launchers else ""}exec {SANDBOX_EXEC} -f "$profile" "$real" "$@"
"""


def command_shim(profile: str, launchers: str = "") -> str:
    """A wrapper that runs the command it is given inside the profile — the interpreter launcher
    Blackbox hands the Hermes agent for its ``execute_code`` Python (Hermes's
    ``HERMES_EXECUTE_CODE_LAUNCHER`` hook point). Already inside a sandbox, or no profile: the
    command runs as it is (fail-open: execute_code always starts; Blackbox reports the level)."""
    return f"""#!/bin/sh
# Blackbox agent sandbox: the Hermes agent's execute_code interpreter — generated by Blackbox (File Shield).
profile={quote_shell(profile)}
if [ "${{BLACKBOX_AGENT_SANDBOX:-}}" = 1 ] || [ ! -r "$profile" ]; then exec "$@"; fi
{pick_profile()}BLACKBOX_AGENT_SANDBOX=1; export BLACKBOX_AGENT_SANDBOX
{with_tools(tools_dir(launchers)) if launchers else ""}exec {SANDBOX_EXEC} -f "$profile" "$@"
"""


