"""The shims first on the sandboxed PATH on Linux: ``brew`` (Linuxbrew) and the package managers —
the POSIX ports' shared ones (``platform/posix_scripts.py``) — the broker's Homebrew run, and the
desktop openers (sandbox permissions ``open-links`` / ``open-apps``): inside, the session bus is
hidden, so ``xdg-open`` and ``gio`` could not open anything; their stand-ins hand a web link
(``xdg-open https://…``, ``gio open https://…``, ``sensible-browser``, ``x-www-browser``) or a file
in a named app (``gio launch <app>.desktop <file>``) to Blackbox's broker. Every other form says
why. ``gio``'s other subcommands (``gio info`` …) run as they are.

Usage::

    brew_shim(tools, python, dashboard_url)
    broker_shims(tools, python, dashboard_url)   # {"xdg-open": …, "gio": …, …}
"""

from __future__ import annotations

from ..posix_scripts import BREW_READ_ONLY, MANAGER_PROGRAMS, brew_shim, manager_shims, quote_shell, spawn_brew, stop_group

#: Where the broker looks for the person's package managers first (``{home}`` filled): Linuxbrew,
#: the person's own tool folders, then the system's.
MANAGER_FOLDERS = ("/home/linuxbrew/.linuxbrew/bin", "{home}/.linuxbrew/bin", "{home}/.volta/bin", "{home}/.cargo/bin",
                   "{home}/.local/bin", "/usr/local/bin", "/usr/bin")
#: Where Linuxbrew's own program is (shared prefix, or one person's).
BREW_PATHS = ("/home/linuxbrew/.linuxbrew/bin/brew", "{home}/.linuxbrew/bin/brew")
#: The browsers' stand-ins: one http(s) link each.
LINK_OPENERS = ("xdg-open", "sensible-browser", "x-www-browser", "www-browser")
REFUSED = ("Blackbox's sandbox refused this ({program}): Blackbox opens a web link (xdg-open https://…) or a file in a named "
           "app (gio launch <app>.desktop file) for agents; anything else, open it yourself.")


def _client(python: str, dashboard_url: str) -> str:
    return f'exec {quote_shell(python)} -I "$tools/brew-client.py" {quote_shell(dashboard_url)}'


def open_shim(tools: str, python: str, dashboard_url: str, program: str = "xdg-open") -> str:
    """The stand-in for one link opener (*program*): one http(s) link goes to the broker."""
    return f"""#!/bin/sh
# Blackbox agent sandbox: {program} — links open through Blackbox (File Shield). Generated by Blackbox.
tools={quote_shell(tools)}
case "${{1:-}}" in
  http://*|https://*) [ "$#" = 1 ] && {_client(python, dashboard_url)} --action open-link "$1" ;;
esac
echo "{REFUSED.format(program=program)}" >&2
exit 126
"""


def gio_shim(tools: str, python: str, dashboard_url: str) -> str:
    """The ``gio`` stand-in: ``open <link>`` and ``launch <app> <files>`` go to the broker, its
    other subcommands run the real ``gio``."""
    client = _client(python, dashboard_url)
    return f"""#!/bin/sh
# Blackbox agent sandbox: gio — links and apps open through Blackbox (File Shield). Generated by Blackbox.
tools={quote_shell(tools)}
case "${{1:-}}" in
  open)
    case "${{2:-}}" in http://*|https://*) [ "$#" = 2 ] && {client} --action open-link "$2" ;; esac
    echo "{REFUSED.format(program="gio open")}" >&2
    exit 126 ;;
  launch)
    shift
    [ "$#" -ge 2 ] && {client} --action open-app -a "$@"
    echo "{REFUSED.format(program="gio launch")}" >&2
    exit 126 ;;
esac
path_rest=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$tools" | paste -sd: -)
real=$(PATH="$path_rest" command -v gio) || {{ echo "gio is not installed" >&2; exit 127; }}
exec "$real" "$@"
"""


def osascript_shim(_tools: str, _python: str, _dashboard_url: str) -> str:
    """No AppleScript on Linux."""
    return ""


def broker_shims(tools: str, python: str, dashboard_url: str) -> dict[str, str]:
    """``{program: stand-in}`` for the brokered actions: the link openers and ``gio``."""
    shims = {program: open_shim(tools, python, dashboard_url, program) for program in LINK_OPENERS}
    shims["gio"] = gio_shim(tools, python, dashboard_url)
    return shims


