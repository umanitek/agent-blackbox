"""The POSIX shell text every Unix port of the agent sandbox shares (macOS and Linux): the
launchers that start a program inside the OS sandbox, the Hermes agent's sandboxed shells and
``execute_code`` launcher, the profile pick by project, and the package-manager shims. Each port
supplies only what differs — its *runner* (the words that start a program inside its sandbox:
``/usr/bin/sandbox-exec -f "$profile"`` on macOS, ``blackbox-sandbox run --policy "$profile" --``
on Linux) and its profile file names.

Shared by name, not by OS: this file sits in ``platform/`` but is no OS's (``kernel.os_layout``
copies it everywhere).

Pattern: **Template Method** — the scripts are fixed; the runner and the suffixes are the steps
a port fills in.

Usage::

    launcher_script("claude", here, profile, runner, tools_dir, Suffixes(".sb", ".once.sb"))
    manager_shims(tools, python, dashboard_url)
"""

from __future__ import annotations

import os
import signal
import subprocess
from dataclasses import dataclass

#: The index of an agent's project profiles beside its profile (``profiles.INDEX``).
PROJECT_INDEX = "projects.idx"
#: The infix of a profile one launch took (``<profile>.run.<pid><suffix>``) and how old an
#: allow-once profile may be when a launch takes it.
RUN_INFIX, ONCE_MINUTES = ".run.", 30


@dataclass(frozen=True)
class Suffixes:
    """One port's profile file names: ``profile`` (``.sb``) and ``once`` (``.once.sb``)."""

    profile: str
    once: str


def quote_shell(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


def with_tools(tools: str) -> str:
    """The shell lines that put the sandbox's tools first on PATH, for the sandboxed program only."""
    return f"""tools={quote_shell(tools)}
if [ -d "$tools" ]; then PATH="$tools:$PATH"; export PATH; fi
"""


def pick_profile(suffixes: Suffixes) -> str:
    """The shell lines that swap ``$profile`` (the agent's own) for its project profile: the LONGEST
    folder in ``<profile without suffix>/projects.idx`` that holds the physical working folder
    (``pwd -P``). The folder goes to awk through the environment, so a backslash in it stays as it
    is; no index, no match or an unreadable file keeps the agent's own profile. Exports the
    profile chosen (``BLACKBOX_SANDBOX_PROFILE``) for the session's records. An allow-once profile
    beside the chosen one (``<profile>`` + *suffixes.once*) is taken by this launch alone: the launch
    that MOVES it to ``<profile>.run.<pid><suffix>`` (a rename: only one of two launches can) runs
    in it, if it is younger than :data:`ONCE_MINUTES`."""
    suffix, once = suffixes.profile, suffixes.once
    return f"""projects="${{profile%{suffix}}}"
if [ -r "$projects/{PROJECT_INDEX}" ]; then
  found=$(BLACKBOX_CWD="$(pwd -P 2>/dev/null)" awk -F '\t' 'BEGIN {{ d = ENVIRON["BLACKBOX_CWD"] }}
    length($1) > n && (d == $1 || index(d, $1 "/") == 1) {{ n = length($1); best = $2 }} END {{ print best }}' "$projects/{PROJECT_INDEX}")
  if [ -n "$found" ] && [ -r "$projects/$found" ]; then profile="$projects/$found"; fi
fi
once="${{profile%{suffix}}}{once}"
if [ -f "$once" ]; then
  taken="${{profile%{suffix}}}{RUN_INFIX}$${suffix}"
  if mv "$once" "$taken" 2>/dev/null; then
    if [ -n "$(find "$taken" -mmin -{ONCE_MINUTES} 2>/dev/null)" ]; then profile="$taken"; else rm -f "$taken"; fi
  fi
fi
digest=$(sed -n '2s/.*sha256:\\([0-9a-f]*\\).*/\\1/p' "$profile" 2>/dev/null)
BLACKBOX_SANDBOX_PROFILE="$profile#$digest"; export BLACKBOX_SANDBOX_PROFILE
"""


def launcher_script(command: str, here: str, profile: str, runner: str, tools: str, suffixes: Suffixes, ready: str = "") -> str:
    """The launcher put first on PATH for *command*: finds the real program further down PATH and
    runs it inside the profile (``exec <runner> "$real" "$@"``), with the sandbox's *tools* folder
    first on ITS PATH. Already inside a sandbox (an agent starting another) it runs the program as
    it is — the sandbox it is in still applies. No profile, or the shell test *ready* (the port's
    "my sandbox program is there", e.g. ``[ -x … ]``) fails: Blackbox's hooks only, said on stderr
    (fail-open: an agent always starts)."""
    return f"""#!/bin/sh
# Blackbox agent sandbox launcher for {command} — generated by Blackbox (File Shield), rewritten on change.
here={quote_shell(here)}
profile={quote_shell(profile)}
path_rest=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$here" | paste -sd: -)
real=$(PATH="$path_rest" command -v {quote_shell(command)}) || {{ echo "blackbox: {command} is not installed" >&2; exit 127; }}
if [ "${{BLACKBOX_AGENT_SANDBOX:-}}" = 1 ]; then exec "$real" "$@"; fi
{pick_profile(suffixes)}if [ -r "$profile" ]{f" && {ready}" if ready else ""}; then
  BLACKBOX_AGENT_SANDBOX=1; export BLACKBOX_AGENT_SANDBOX
  {with_tools(tools).strip().replace(chr(10), chr(10) + "  ")}
  exec {runner} "$real" "$@"
fi
echo "blackbox: no sandbox profile — {command} runs with Blackbox's hooks only" >&2
exec "$real" "$@"
"""


def shell_shim(shell: str, here: str, profile: str, runner: str, tools: str, suffixes: Suffixes, ready: str = "") -> str:
    """A ``bash`` / ``sh`` / ``zsh`` that runs the real shell inside the profile — put first on the
    Hermes agent's OWN PATH (never the person's), so every shell its terminal tool starts is inside
    the sandbox while the Hermes process itself (and Blackbox in it) stays outside. *tools*: the
    sandbox-tools folder first on the sandboxed shell's PATH ("" for none); *ready* as for
    :func:`launcher_script` (it fails: the real shell, as without a profile)."""
    return f"""#!/bin/sh
# Blackbox agent sandbox: {shell} for the Hermes agent's tools — generated by Blackbox (File Shield).
here={quote_shell(here)}
profile={quote_shell(profile)}
path_rest=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$here" | paste -sd: -)
real=$(PATH="$path_rest" command -v {quote_shell(shell)}) || real=/bin/{shell}
if [ "${{BLACKBOX_AGENT_SANDBOX:-}}" = 1 ] || [ ! -r "$profile" ]{f" || ! {ready}" if ready else ""}; then exec "$real" "$@"; fi
{pick_profile(suffixes)}BLACKBOX_AGENT_SANDBOX=1; export BLACKBOX_AGENT_SANDBOX
{with_tools(tools) if tools else ""}exec {runner} "$real" "$@"
"""


def command_shim(profile: str, runner: str, tools: str, suffixes: Suffixes, ready: str = "") -> str:
    """A wrapper that runs the command it is given inside the profile — the interpreter launcher
    Blackbox hands the Hermes agent for its ``execute_code`` Python (Hermes's
    ``HERMES_EXECUTE_CODE_LAUNCHER`` hook point). Already inside a sandbox, or no profile: the
    command runs as it is (fail-open: execute_code always starts; Blackbox reports the level)."""
    return f"""#!/bin/sh
# Blackbox agent sandbox: the Hermes agent's execute_code interpreter — generated by Blackbox (File Shield).
profile={quote_shell(profile)}
if [ "${{BLACKBOX_AGENT_SANDBOX:-}}" = 1 ] || [ ! -r "$profile" ]{f" || ! {ready}" if ready else ""}; then exec "$@"; fi
{pick_profile(suffixes)}BLACKBOX_AGENT_SANDBOX=1; export BLACKBOX_AGENT_SANDBOX
{with_tools(tools) if tools else ""}exec {runner} "$@"
"""


def standin(name: str, note: str) -> str:
    """A stand-in for a setuid program that can not run inside the sandbox: it says why (*note*)."""
    return f"""#!/bin/sh
# Blackbox agent sandbox: {name} is setuid and can not run inside the sandbox — generated by Blackbox (File Shield).
echo "Blackbox's sandbox refused this ({name}): {note}." >&2
exit 126
"""


#: The Homebrew commands that only read, run as they are inside the sandbox; ``tap`` alone lists the taps.
BREW_READ_ONLY = ("list", "ls", "info", "abv", "search", "-S", "deps", "uses", "outdated", "config", "doctor", "dr", "--version",
                  "-v", "--prefix", "--cellar", "--repository", "--repo", "--cache", "--caskroom", "--env", "home", "homepage",
                  "desc", "leaves", "commands", "help", "-h", "--help", "log", "cat", "formulae", "casks", "options", "missing",
                  "shellenv", "tap-info", "which-formula", "")


def brew_shim(tools: str, python: str, dashboard_url: str) -> str:
    """The ``brew`` first on the sandboxed PATH (KI-593): a command that changes what is installed
    goes to Blackbox's broker through the client beside it (``packages/client.py``); a command that
    only reads (:data:`BREW_READ_ONLY`) runs the real Homebrew inside the sandbox; EVERY other
    command — ``tap`` / ``untap`` (a tap is code from anywhere), ``link``, ``unlink``, ``pin``,
    ``services``, ``update``, ``cleanup``… — writes Homebrew's prefix, which the sandbox keeps closed
    (security round 4: ``brew tap someone/evil-tap`` began cloning from inside), and is refused with
    the reason."""
    read_only = "|".join(f'"{verb}"' if verb else '""' for verb in BREW_READ_ONLY)
    return f"""#!/bin/sh
# Blackbox agent sandbox: brew — installs go through Blackbox (File Shield). Generated by Blackbox.
tools={quote_shell(tools)}
case "${{1:-}}" in
  install|upgrade|reinstall|uninstall|remove|rm)
    exec {quote_shell(python)} -I "$tools/brew-client.py" {quote_shell(dashboard_url)} "$@" ;;
  tap)
    if [ "$#" -gt 1 ]; then
      echo "Blackbox's sandbox refused this (brew tap): a tap adds formulae from outside Homebrew's official taps and changes Homebrew; run it in your own terminal if you trust it." >&2
      exit 126
    fi ;;
  {read_only}) ;;
  *)
    echo "Blackbox's sandbox refused this (brew ${{1}}): it changes Homebrew, which the agent sandbox keeps closed; Blackbox installs, upgrades and removes packages for you, run anything else in your own terminal." >&2
    exit 126 ;;
esac
path_rest=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$tools" | paste -sd: -)
real=$(PATH="$path_rest" command -v brew) || {{ echo "brew is not installed" >&2; exit 127; }}
exec "$real" "$@"
"""


#: When each package manager's words are a global install Blackbox does (``packages.managers``):
#: a POSIX test that sets ``broker=1``. Everything else runs the real program inside the sandbox.
_GLOBAL_TESTS = {
    "npm": ('global=0; verb=\nfor word in "$@"; do case "$word" in -g|--global) global=1 ;; -*) ;; *) [ -z "$verb" ] && verb=$word ;; esac; done\n'
            'case "$verb" in install|i|add|uninstall|un|rm|remove|update|up) [ "$global" = 1 ] && broker=1 ;; esac'),
    "pipx": 'case "${1:-}" in install|uninstall|upgrade) broker=1 ;; esac',
    "pip": 'case " $* " in *" --user "*) [ "${1:-}" = install ] && broker=1 ;; esac',
    "cargo": 'case "${1:-}" in install|uninstall) broker=1 ;; esac',
    "gem": 'case "${1:-}" in install|uninstall) broker=1 ;; esac',
    "uv": '[ "${1:-}" = tool ] && case "${2:-}" in install|uninstall|upgrade) broker=1 ;; esac',
}
#: The program names each manager's shim stands in for.
MANAGER_PROGRAMS = {"npm": ("npm",), "pipx": ("pipx",), "pip": ("pip", "pip3"), "cargo": ("cargo",), "gem": ("gem",), "uv": ("uv",)}


def manager_shims(tools: str, python: str, dashboard_url: str) -> dict[str, str]:
    """``{program: shim}`` for the package managers (sandbox permission ``global-installs``): a
    global install goes to Blackbox's broker through the client beside it; every other use runs
    the real program inside the sandbox, as it is."""
    shims = {}
    for manager, programs in MANAGER_PROGRAMS.items():
        for program in programs:
            shims[program] = f"""#!/bin/sh
# Blackbox agent sandbox: {program} — global installs go through Blackbox (File Shield). Generated by Blackbox.
tools={quote_shell(tools)}
broker=0
{_GLOBAL_TESTS[manager]}
if [ "$broker" = 1 ]; then exec {quote_shell(python)} -I "$tools/brew-client.py" {quote_shell(dashboard_url)} --manager {manager} "$@"; fi
path_rest=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$tools" | paste -sd: -)
real=$(PATH="$path_rest" command -v {program}) || {{ echo "{program} is not installed" >&2; exit 127; }}
exec "$real" "$@"
"""
    return shims


def spawn_brew(command: list[str], env: dict[str, str], cwd: str) -> subprocess.Popen[str]:
    """Starts the brokered Homebrew run (``packages.jobs``): no stdin, output and errors as one text
    stream, its own process group (so :func:`stop_group` stops brew and every child it started)."""
    return subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env, cwd=cwd,
                            text=True, encoding="utf-8", errors="replace", start_new_session=True)


def stop_group(process: subprocess.Popen[str]) -> None:
    """Stops a run :func:`spawn_brew` started, with everything in its process group."""
    try:
        os.killpg(process.pid, signal.SIGTERM)   # windows-footgun: ok (POSIX ports only)
    except OSError:
        pass


